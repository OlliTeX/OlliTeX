import { chromium } from 'playwright';
const BASE = 'http://127.0.0.1:7420';
const st = JSON.parse((await import('node:fs')).readFileSync('/tmp/ol_probe1.json', 'utf8'));
const PID = st.pid;
const sid = st.cookie.split('overleaf.sid=')[1].split(';')[0];
console.log('sid value:', sid ? sid.slice(0, 30) + '...' : 'EXTRACT-FAILED', 'len', sid?.length);
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addCookies([{ name: 'overleaf.sid', value: sid, url: BASE }]);
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', e => errs.push('pageerror: ' + String(e).slice(0, 300)));
page.on('console', m => { if (m.type() === 'error') errs.push('console: ' + m.text().slice(0, 300)); });
const resp = [];
page.on('response', r => { if (r.status() >= 400) resp.push(r.status() + ' ' + r.url().slice(0, 80)); });
await page.goto(BASE + '/editor/' + PID, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(12000);
console.log('URL now:', page.url());
console.log('TITLE:', await page.title());
const bodyTxt = (await page.locator('body').innerText()).slice(0, 400);
console.log('BODY:', JSON.stringify(bodyTxt));
console.log('cm-content count:', await page.locator('.cm-content').count());
console.log('errs (first 8):', JSON.stringify(errs.slice(0, 8), null, 1));
console.log('bad responses:', JSON.stringify(resp.slice(0, 8)));
await page.screenshot({ path: '/tmp/f1-debug.png' });
await browser.close();
