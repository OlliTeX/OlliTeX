const { chromium } = require('playwright')
const BASE = process.argv[2]
;(async () => {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ baseURL: BASE })
  const page = await ctx.newPage()
  await page.goto('/login')
  await page.fill('#email', 'e2e-user@e2e.test')
  await page.fill('#password', 'Ol-Fixture-3m2Q')
  const resp = await page.click('button[type=submit]')
  await page.waitForTimeout(2500)
  console.log('response after submit:', resp && resp.status(), resp && resp.headers()['location'])
  console.log('URL:', page.url())
  const body = await page.locator('body').innerText()
  console.log('page text (150):', body.slice(0, 150).replace(/\n/g, ' | '))
  const form = await page.locator('form').getAttribute('action').catch(() => 'n/a')
  console.log('form action:', form)
  const inputs = await page.locator('input').evaluateAll((els) => els.map((e) => e.type + ':' + e.name + ':' + (e.value ? 'set' : 'empty')))
  console.log('inputs:', inputs.join(', '))
  await browser.close()
})().catch((e) => { console.error('ERR', e.message); process.exit(1) })
